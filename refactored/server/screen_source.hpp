#pragma once
// ============================================================
// 屏幕源抽象接口
//
// 第三阶段的替换点就在这里：把 GdiScreenCapturer（BitBlt + PNG）
// 换成 DxgiScreenSource（Desktop Duplication + 脏矩形 + H.264）。
// 只要签名不变，Session / AsioServer / 协议层一行都不用改。
//
// 注意 capture 是阻塞调用（GDI 抓屏 + PNG 编码是实打实的 CPU 活），
// 因此绝不能在 asio 的 io 线程上直接调用 —— 见 AsioServer 里的 capture 线程池。
//
// 【差异帧（第三阶段第一步）为什么把 consumer_id 放进接口】
//   同一个 capturer 被**所有会话共享**，而每个会话收到的帧序列各不相同：
//   A 拿到第 5 帧、B 拿到的可能是第 8 帧。差异帧必须相对"这个客户端手上已有的
//   那张图"来算，所以基准帧只能按消费者分别保存 —— 若只维护一份全局"上一帧"，
//   第二个客户端就会把增量贴到错误的基准上，画面从此永久错乱（而且不报任何错）。
//   DXGI 原生就给脏矩形，实现里同样要按消费者保存基准纹理，所以这条参数在替换后依然成立。
// ============================================================

#include <chrono>
#include <cstdint>
#include <vector>

namespace rc::server {

/// 一帧抓屏结果。宽高必须由实现方一并给出 ——
/// 让调用方去解析 PNG 头拿尺寸是没必要的耦合。
struct CapturedFrame {
    std::vector<char> data;             ///< 编码后的图像字节

    /// 【注意语义】永远是**整屏**尺寸，不是 data 的尺寸。
    /// 差异帧时 data 只承载脏区域那一小块，客户端要靠整屏尺寸做坐标映射与缩放。
    std::int32_t      width  = 0;
    std::int32_t      height = 0;

    // ---- 差异帧（第三阶段）----
    /// true  = data 只是 rect 那块区域的图，客户端应把它贴到累积画面的对应位置；
    /// false = data 是完整一帧，客户端直接整体替换。
    ///
    /// 特例：delta=true 且 data 为空 = "这一帧没有任何变化"。之所以还要发一个空帧，
    /// 是因为协议是**请求-应答**拉屏：客户端收到一帧才请求下一帧，服务端不回的话
    /// 客户端就永远停在等待上（表现为画面冻结而不是"没变化"）。
    bool         delta = false;
    std::int32_t rect_x = 0;            ///< 脏区域左上角（整屏坐标系）
    std::int32_t rect_y = 0;
    std::int32_t rect_w = 0;            ///< 脏区域宽高
    std::int32_t rect_h = 0;

    // ---- 性能归因（第三阶段第二步）：只做观测，不参与任何逻辑判断 ----
    /// 服务端收到触发这次抓屏的那个 ScreenRequest 的时刻。
    ///
    /// 为什么要把它带进来：抓屏器每 5 秒会打一条分段耗时，但"分段之和"远小于
    /// 真实帧周期（实测 22.4 ms vs 47.2 ms）—— 中间那 24.8 ms 是**空档**，
    /// 而不是某一项慢。空档有两个来源，必须分开：① 限流等待（请求来得太早，
    /// 被 next_capture_at_ 挡住）；② 定时器到点后回调实际被调度的延迟。
    /// 前者是设计，后者是 Windows 时钟粒度问题，而两者只能靠这个时间戳区分。
    std::chrono::steady_clock::time_point request_at{};

    // ---- 输入→显示延迟（第三阶段第 2 步 2b）：只做观测，不参与任何逻辑判断 ----
    /// 本帧像素**开始采集之前**，本会话已应用过的输入事件累计数（下界语义）。
    ///
    /// 必须在 `capture()` **之前**读它：这样"带该值的帧"的像素一定落在这些输入之后，
    /// 客户端才敢把它当成那些输入的"首次可见帧"。反过来读会把"抓屏期间才应用的输入"
    /// 也算进去 —— 客户端于是把一帧并不包含该输入的画面认成它的显示，延迟被系统性
    /// 报小，而报小是唯一危险的方向（报大只是保守）。
    std::int64_t input_epoch = 0;

    /// 最近一次输入应用完成 → 本次抓屏开始 的空档（毫秒）。
    /// 负值 = 这一拍没有可用的输入（没有输入应用，或竞态产物被过滤掉）。
    /// 它是"输入→显示"里最可能的大头：抓屏是按客户端请求驱动的，
    /// 输入落在两次抓屏之间就得等下一拍，等待时长由帧周期决定。
    double input_gap_ms = -1.0;

    /// 本次抓屏时系统光标是否可见（`CURSOR_SHOWING`）。
    /// 用来做一条前置不变式：光标被隐藏时（Windows 的"打字时隐藏指针"、
    /// 或全屏应用接管了指针），`capture_cursor` 打开也合成不出光标，
    /// 于是"移动光标"这类输入**在画面里根本不可见** ——
    /// 那种情况下测出来的延迟数字是假的，必须报"没测到"而不是报一个好看的数。
    bool cursor_visible = false;
};

class IScreenSource {
public:
    virtual ~IScreenSource() = default;

    /// 抓取一帧。
    /// @param consumer_id 消费者（会话）标识 —— 差异帧的基准帧按它分别维护，
    ///        详见文件头注释。整帧模式下该参数被忽略。
    /// @return 失败返回 false（例如会话被锁定、处于安全桌面）。
    virtual bool capture(CapturedFrame& out, std::uint32_t consumer_id) = 0;

    /// 会话结束时释放它占用的基准帧。
    /// 默认空实现：无状态的实现（如测试替身、一次性抓屏）不需要理会。
    /// 不释放的话，每个连过的客户端都会留下 6.5 MB 的基准位图（1707×960×4B）。
    virtual void release_consumer(std::uint32_t consumer_id) noexcept { (void)consumer_id; }

    /// 供日志显示的实现名（如 "gdi+png"）
    virtual const char* name() const noexcept = 0;
};

} // namespace rc::server
