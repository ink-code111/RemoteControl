#pragma once
// ============================================================================
//  tls —— 2B 第二刀：TLS 上下文与证书工具
//
//  【这一刀要解决的问题】
//    第一刀（auth_token）只回答"谁能连上这个端口"，凭据本身是**明文传输**的
//    （§6.23(7) 已明确记账）。这一刀把整条链路加密，于是：
//      · 链路上的抓包看不到鼠标/键盘/画面，也看不到 auth_token；
//      · 中间人无法冒充服务端（客户端 pin 住服务端证书指纹）。
//
//  【证书模型：自签 + 指纹 pin（用户拍板）】
//    没有 CA、不需要用户先准备证书：
//      · 服务端首次启动时**自签**一套（cert/key 写盘，之后复用）；
//      · 客户端 **pin** 服务端证书的 SHA-256 指纹。
//    为什么不走"系统 CA 信任链"：本项目是两台自备机器之间的点对点工具，
//    搭私有 CA 的运维成本远大过收益；而 pin 的强度在"防中间人"这件事上
//    **不弱于** CA（只要指纹是通过可信信道带过去的）。代价换证书 = 要同步改
//    客户端配置 —— 对一个自用工具，这是可以接受的取舍，且**必须显式记账**。
//
//  【为什么指纹要能被读回来】
//    服务端启动时会把**自己证书的指纹**打进日志 —— 客户端配置里的
//    `tls_pin_sha256` 就抄这个值。这是本项目 §6.12 那条"配了就要能自证生效"
//    在这里的落点：没有它，用户只能靠外部 openssl 命令去算，而那个命令
//    未必在目标机器上有（本机上它只是 PortableGit 顺手带的）。
// ============================================================================

// ⚠️ 必须先经过 asio_common.hpp 再含 asio：前者负责定义 ASIO_STANDALONE 与
//    _WIN32_WINNT（本工程用 standalone Asio；缺后者 MSVC 会按 Win7 目标降级并报警）。
//    顺序反了会得到一堆 "请在包含 windows.h 之前定义 _WIN32_WINNT" 的告警。
#include "asio_common.hpp"

#include <asio/ssl.hpp>

#include <cstddef>
#include <memory>
#include <string>

namespace rc::tls {

// ---------------------------------------------------------------------------
//  版本自证：本工程唯一的**预编译二进制**依赖，其特有失效模式是
//  "头文件与 lib/DLL 版本不一致"（能编过、能链接，运行期行为不可解释）。
// ---------------------------------------------------------------------------
/// 链接进来的 OpenSSL **运行期**版本，来自 DLL 自身。
std::string runtime_version();
/// 编译期**头文件**里写死的版本（`OPENSSL_VERSION_TEXT`）。两者必须同版本。
std::string build_version();

// ---------------------------------------------------------------------------
//  指纹
// ---------------------------------------------------------------------------
/// 从 PEM 证书文件读取并算指纹（"AA:BB:CC:…"，大写、冒号分隔）。失败返回空串并写 `*error`。
///
/// 服务端启动时把**自己证书**的指纹打进日志，客户端抄那一行填 `tls_pin_sha256`。
///
/// ⚠️ 这里刻意**只暴露这一个**指纹工具。计算"对端证书的指纹"只发生在 tls.cpp 内部
///    （`make_client_context` 的校验回调里），所以没有必要把更低层的"算/格式化"助手
///    放到头文件上。这不是洁癖，是有代价的：
///    最初的版本暴露了一个 `fingerprint_sha256(bytes, len)`（语义 = 把给定字节
///    **再算一次** SHA-256 并格式化），而回调里拿到的已经是**算好的摘要**，
///    于是被又哈希了一遍 —— 两边产出的都是合法的 64 位十六进制、肉眼无从分辨，
///    只是**永远不可能相等**。这个 bug 让 pin 校验退化成"永远拒绝"，
///    而所有"配了 pin 就该连上"的检查都会看不出异常（错的一侧只是拒绝得更早）。
///    ⇒ **名字与契约必须写明"算"还是"只格式化"**，别让调用方猜。
std::string fingerprint_of_pem_file(const std::string& cert_file, std::string* error);

/// 把用户写在配置里的指纹规范化（去空白、去冒号、转大写）后比较。
///
/// 【为什么要规范化而不是直接字符串比较】用户在配置里抄指纹时，大小写、
/// 冒号、空格、"sha256:" 前缀都可能不一样；直接比较会得到一个"配了但永远不匹配"
/// 的开关 —— 那正是本项目最怕的**静默失效**（§8.6 / §8.12 / §6.14 / §8.21）。
/// 所以比较前一律规整成"无分隔符的大写十六进制"。
bool fingerprint_matches(const std::string& configured, const std::string& actual);
/// 规范化后的指纹（去分隔符、转大写）。空串输入得空串。
std::string normalize_fingerprint(const std::string& fp);

// ---------------------------------------------------------------------------
//  自签证书
// ---------------------------------------------------------------------------
/// 确保 cert_file / key_file 存在；缺任一则自签一对写入（PEM，RSA-2048，
/// 有效期 10 年，含 SAN=localhost/127.0.0.1，仅 serverAuth）。
/// 已存在则原样保留（**绝不覆盖** —— 覆盖会让所有已 pin 的客户端失效）。
/// 返回 false 时写 `*error`。
bool ensure_self_signed_cert(const std::string& cert_file, const std::string& key_file,
                             std::string* error);

// ---------------------------------------------------------------------------
//  上下文
// ---------------------------------------------------------------------------
/// 服务端 ssl::context：加载 cert/key，最低 TLS 1.2。
/// 失败返回 nullptr 并写 `*error`。
std::shared_ptr<asio::ssl::context>
make_server_context(const std::string& cert_file, const std::string& key_file, std::string* error);

/// 客户端 ssl::context。
///
/// @param expected_fingerprint 期望的服务端证书 SHA-256 指纹（任意分隔形式都行）。
///        非空时启用校验回调：握手过程中把对端证书的指纹算出来对比，
///        不匹配即**中止握手**（客户端表现为握手失败 ⇒ 不可重试）。
///        为空 = 不校验对端身份（**危险**：只加密不认证，防得住窃听、防不住中间人）；
///        调用方必须为此大声告警 —— 本项目不允许静默的"看起来安全"。
std::shared_ptr<asio::ssl::context>
make_client_context(const std::string& expected_fingerprint, std::string* error);

} // namespace rc::tls
